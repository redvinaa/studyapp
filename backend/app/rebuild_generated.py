"""Re-embed legacy generated references without resetting subtopics or failed cards.

Run once after backing up SQLite. Concurrently changing topics are skipped.
Existing citation ranges are mapped into the new display text where possible;
otherwise the file link is retained without a potentially incorrect line range.
"""
from collections import defaultdict
from pathlib import Path
import json
from .db import db, UPLOADS
from .source_files import generated_filename, generated_reference
from .ingestion import extract
from .ai import embeddings, MODEL


def previous_view(raw,description,first_chunk):
    prefix=('# AI-generated study material\n\n'
            '> These notes were generated by AI from the description below. Verify important facts against reliable sources.\n\n'
            '## Description\n\n'+description+'\n\n## Notes\n\n')
    if not raw.startswith(prefix):
        return raw
    if 'from the description below' in first_chunk:
        return raw
    if 'These notes were generated by AI.' in first_chunk:
        return ('# AI-generated study material\n\n'
                '> These notes were generated by AI. Verify important facts against reliable sources.\n\n'
                '## Reference\n\n'+raw[len(prefix):])
    return None


def remap_range(source,old_text,new_text):
    if old_text is None or not isinstance(source.get('line_start'),int) or not isinstance(source.get('line_end'),int):
        source['line_start']=source['line_end']=None
        return
    old=old_text.splitlines();new=new_text.splitlines();common=0
    while common<min(len(old),len(new)) and old[-1-common]==new[-1-common]:
        common+=1
    old_start=len(old)-common+1;new_start=len(new)-common+1
    begin,end=source['line_start'],source['line_end']
    if not common or end<old_start:
        source['line_start']=source['line_end']=None
    else:
        source['line_start']=new_start if begin<old_start else begin-old_start+new_start
        source['line_end']=min(len(new),end-old_start+new_start)


def rebuild():
    with db() as c:
        rows=[dict(r) for r in c.execute("""SELECT f.*,(SELECT g.description FROM material_generations g
                 WHERE g.file_id=f.id ORDER BY g.id DESC LIMIT 1) generated_description,
                 (SELECT g.requested_name FROM material_generations g WHERE g.file_id=f.id ORDER BY g.id DESC LIMIT 1) requested_name,
                 (SELECT g.concept_name FROM material_generations g WHERE g.file_id=f.id ORDER BY g.id DESC LIMIT 1) concept_name,
                 t.index_revision,t.index_status FROM files f JOIN topics t ON t.id=f.topic_id
                 WHERE EXISTS (SELECT 1 FROM material_generations g WHERE g.file_id=f.id)""")]
    grouped=defaultdict(list)
    for f in rows:
        raw=Path(UPLOADS,f['storage_key']).read_text(encoding='utf-8')
        title=generated_filename(f['original_name'],f['generated_description'],f['requested_name'],f['concept_name'])
        view=generated_reference(raw,f['generated_description'],title)
        if view != raw:
            with db() as c:
                first=c.execute('SELECT content FROM chunks WHERE file_id=? ORDER BY ordinal LIMIT 1',(f['id'],)).fetchone()
            first_expected=' '.join(view.split()[:30])
            if first and first[0].startswith(first_expected):
                continue
            f['raw_text']=raw;f['view_text']=view;f['display_name']=title
            grouped[f['topic_id']].append(f)
    for topic_id,files in grouped.items():
        with db() as c:
            if c.execute("SELECT 1 FROM ingestion_jobs WHERE topic_id=? AND status IN ('queued','running')",(topic_id,)).fetchone():
                print(f'Topic {topic_id}: skipped; indexing is in progress.')
                continue
            for f in files:
                first=c.execute('SELECT content FROM chunks WHERE file_id=? ORDER BY ordinal LIMIT 1',(f['id'],)).fetchone()
                f['old_view']=previous_view(f['raw_text'],f['generated_description'],first[0] if first else '')
        replacements=[]
        for f in files:
            chunks=extract(f)
            vectors=embeddings([x[0] for x in chunks])
            replacements.append((f,chunks,vectors))
        with db() as c:
            c.execute('BEGIN IMMEDIATE')
            topic=c.execute('SELECT index_revision,index_status FROM topics WHERE id=?',(topic_id,)).fetchone()
            if not topic or topic['index_revision']!=files[0]['index_revision'] or topic['index_status']!=files[0]['index_status']:
                print(f'Topic {topic_id}: skipped; topic changed while preparing replacement chunks.')
                continue
            if c.execute("SELECT 1 FROM ingestion_jobs WHERE topic_id=? AND status IN ('queued','running')",(topic_id,)).fetchone():
                print(f'Topic {topic_id}: skipped; indexing started during preparation.')
                continue
            if any(not c.execute('SELECT 1 FROM files WHERE id=? AND sha256=? AND storage_key=?',(f['id'],f['sha256'],f['storage_key'])).fetchone() for f in files):
                print(f'Topic {topic_id}: skipped; a source file changed.')
                continue
            by_id={f['id']:f for f in files}
            cards=c.execute('SELECT fc.id,fc.sources_json FROM failed_cards fc JOIN subtopics s ON s.id=fc.subtopic_id WHERE s.topic_id=?',(topic_id,)).fetchall()
            for card in cards:
                sources=json.loads(card['sources_json']);changed=False
                for source in sources:
                    f=by_id.get(source.get('file_id'))
                    if f:
                        source['filename']=f['display_name']
                        remap_range(source,f['old_view'],f['view_text'])
                        changed=True
                if changed:c.execute('UPDATE failed_cards SET sources_json=? WHERE id=?',(json.dumps(sources),card['id']))
            for f,chunks,vectors in replacements:
                c.execute('DELETE FROM chunks WHERE file_id=?',(f['id'],))
                for ordinal,(chunk,vector) in enumerate(zip(chunks,vectors)):
                    c.execute('INSERT INTO chunks(file_id,ordinal,content,page_start,page_end,line_start,line_end,embedding,embedding_model) VALUES(?,?,?,?,?,?,?,?,?)',(f['id'],ordinal,*chunk,vector.tobytes(),MODEL))
            c.execute('UPDATE topics SET index_revision=index_revision+1 WHERE id=?',(topic_id,))
        print(f'Topic {topic_id}: refreshed {len(files)} generated reference file(s); progress and failed cards preserved.')

if __name__=='__main__':
    rebuild()
