"""Present generated reference files with descriptive titles and no copied request."""
import re

def generated_filename(original_name, description=None, requested_name=None, concept_name=None):
    name=(requested_name or concept_name or '').strip()
    if not name:
        name=re.sub(r'\s*\(AI-generated\)(?=\.md$)', '',original_name,flags=re.IGNORECASE)
        if re.fullmatch(r'AI-generated material\s+\d+\.md',name,flags=re.IGNORECASE):
            name=(description or 'Study material').split('\n')[0][:80]
    name=' '.join(name.replace('/',' ').replace('\\',' ').split()).strip('. ') or 'Study material'
    if name.lower().endswith('.md'):
        name=name[:-3].strip('. ') or 'Study material'
    return name+'.md'

def generated_reference(text, description, title=None):
    legacy=('# AI-generated study material\n\n'
            '> These notes were generated by AI from the description below. Verify important facts against reliable sources.\n\n'
            '## Description\n\n' + (description or '') + '\n\n## Notes\n\n')
    newer=('# AI-generated study material\n\n'
           '> These notes were generated by AI. Verify important facts against reliable sources.\n\n'
           '## Reference\n\n')
    if description and text.startswith(legacy): body=text[len(legacy):]
    elif text.startswith(newer): body=text[len(newer):]
    else: return text
    body=re.sub(r'^#\s+[^\n]+\n+','',body,count=1)
    title=(title or 'Study material').removesuffix('.md')
    return '# '+title+'\n\n'+body
