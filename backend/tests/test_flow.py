def test_grade_count_tracks_answers_not_skips_or_retries():
    from app import study
    from app.db import db
    with TestClient(app,base_url='https://testserver',headers={'origin':'https://testserver'}) as c:
        c.post('/api/login',json={'password':'correct'})
        course=c.post('/api/courses',json={'name':'Progress threshold'}).json()['id']
        topic=c.post(f'/api/courses/{course}/topics',json={'name':'Threshold'}).json()['id']
        c.post(f'/api/topics/{topic}/files',files={'files':('test.txt',b'Motion is change in position over time.','text/plain')})
        for _ in range(100):
            tree=next(x for x in c.get('/api/tree').json() if x['id']==course);t=tree['topics'][0]
            if t['index_status']=='ready': break
            time.sleep(.05)
        sid=study.create('topic',topic)
        sub=t['subtopics'][0]
        for i in range(10):
            token=f'token-{i}'
            with study.lock:
                study.sessions[sid]['current']={'card_token':token,'subtopic_id':sub['id'],'failed_id':None,'revision':t['index_revision'],'topic_id':topic,'question_type':'recall','front':'Q','back':'A','sources':[]}
            status,response=study.grade(sid,token,True)
            assert status=='ok'
            assert study.grade(sid,token,True)[1]==response
            tree=next(x for x in c.get('/api/tree').json() if x['id']==course);t=tree['topics'][0]
            assert tree['graded_count']==t['graded_count']==t['subtopics'][0]['graded_count']==i+1
        with study.lock:
            study.sessions[sid]['current']={'card_token':'skip','subtopic_id':sub['id'],'failed_id':None,'revision':t['index_revision']}
        study.grade(sid,'skip',None)
        assert next(x for x in c.get('/api/tree').json() if x['id']==course)['graded_count']==10
