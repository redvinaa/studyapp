def test_legacy_reference_extraction_and_rebuild_preserve_progress(monkeypatch):
    import hashlib
    from pathlib import Path
    from app.db import db,UPLOADS
    from app import rebuild_generated
    description='Run exercise line 12 and inspect a particular file.'
    legacy=('# AI-generated study material\n\n> These notes were generated by AI from the description below. Verify important facts against reliable sources.\n\n## Description\n\n'+description+'\n\n## Notes\n\n- Lossless compression reconstructs every original byte.\n')
    monkeypatch.setattr(rebuild_generated,'embeddings',fake_embedding)
    with TestClient(app,base_url='https://testserver',headers={'origin':'https://testserver'}) as c:
        c.post('/api/login',json={'password':'correct'})
        course=c.post('/api/courses',json={'name':'Existing reference repair'}).json()['id']
        topic=c.post(f'/api/courses/{course}/topics',json={'name':'Compression'}).json()['id']
        key='legacy_test_reference';Path(UPLOADS,key).write_text(legacy)
        with db() as con:
            fid=con.execute('INSERT INTO files(topic_id,original_name,storage_key,sha256,mime_type,size_bytes,status) VALUES(?,?,?,?,?,?,?)',(topic,'legacy.md',key,hashlib.sha256(legacy.encode()).hexdigest(),'text/plain',len(legacy),'ready')).lastrowid
            con.execute("INSERT INTO material_generations(topic_id,description,status,file_id) VALUES(?,?,'complete',?)",(topic,description,fid))
            sid=con.execute("INSERT INTO subtopics(topic_id,name,description,proficiency,graded_count) VALUES(?,?,?,0.6,12)",(topic,'Compression','Lossless compression')).lastrowid
            con.execute("INSERT INTO chunks(file_id,ordinal,content,embedding,embedding_model) VALUES(?,0,?,?,?)",(fid,description,fake_embedding(['x'])[0].tobytes(),study.MODEL))
            import json
            failed=con.execute('INSERT INTO failed_cards(subtopic_id,question_type,front,back,sources_json) VALUES(?,?,?,?,?)',(sid,'recall','Question','Answer',json.dumps([{'file_id':fid,'filename':'legacy.md','line_start':1,'line_end':10}]))).lastrowid
            con.execute("UPDATE topics SET index_status='ready' WHERE id=?",(topic,))
        displayed=c.get('/api/files/'+str(fid)).text
        assert description not in displayed and 'every original byte' in displayed
        rebuild_generated.rebuild()
        with db() as con:
            sub=con.execute('SELECT proficiency,graded_count FROM subtopics WHERE id=?',(sid,)).fetchone()
            chunks=[r[0] for r in con.execute('SELECT content FROM chunks WHERE file_id=?',(fid,))]
            saved=con.execute('SELECT front,back,sources_json FROM failed_cards WHERE id=?',(failed,)).fetchone()
        assert sub['proficiency']==0.6 and sub['graded_count']==12
        assert saved['front']=='Question' and saved['back']=='Answer'
        assert json.loads(saved['sources_json'])[0]['file_id']==fid
        assert all(description not in chunk for chunk in chunks)
        assert any('every original byte' in chunk for chunk in chunks)
        rebuild_generated.rebuild()
        with db() as con:
            assert con.execute('SELECT COUNT(*) FROM failed_cards WHERE id=?',(failed,)).fetchone()[0]==1


